"""Exercise model suggestions only inside the pilot's hidden native test host."""
import argparse
import json
from pathlib import Path
import time
import urllib.request
import urllib.parse
import uuid

ROOT = Path(__file__).resolve().parents[2]
LOCAL = ROOT / '.local/ygo-agent-pilot'


def validate_service(service, runtime):
    if service.get('embedded') is not True or Path(service.get('runtime', '')).resolve() != runtime.resolve():
        raise ValueError('Service does not belong to the isolated pilot runtime')


def read_deck(path):
    deck = {'main': [], 'extra': [], 'side': []}
    zone = 'main'
    for line in path.read_text(encoding='utf-8').splitlines():
        if line == '#extra': zone = 'extra'
        elif line == '!side': zone = 'side'
        elif line.isdecimal(): deck[zone].append(int(line))
    # Upstream places generated tokens in its side section for preloading.
    # This test uses the public main/extra deck; tokens are generated by the core.
    deck['side'] = []
    return deck


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--runtime', type=Path, required=True)
    parser.add_argument('--url', required=True)
    parser.add_argument('--case', choices=['baseline', 'single-starter', 'ash'], default='baseline')
    args = parser.parse_args()
    expected = (LOCAL / 'desktop-check-development-modular/runtime').resolve()
    if args.runtime.resolve() != expected:
        raise ValueError('An isolated pilot runtime is required')
    if urllib.parse.urlparse(args.url).hostname != '127.0.0.1':
        raise ValueError('Only the local acceptance service is allowed')
    service = json.load(urllib.request.urlopen(args.url + '/api/bootstrap'))
    validate_service(service, expected)
    token = service['token']

    def api(path, body=None):
        request = urllib.request.Request(args.url + path,
            data=json.dumps(body).encode() if body is not None else None,
            headers={'Content-Type': 'application/json', 'X-Trainer-Token': token})
        try:
            with urllib.request.urlopen(request, timeout=90) as response: return json.load(response)
        except urllib.error.HTTPError as error:
            raise RuntimeError(error.read().decode()) from error

    deck = read_deck(LOCAL / 'TenyiSword.ydk')
    opponent = read_deck(LOCAL / 'BlueEyes.ydk')
    hand = [20001443, 93490856, 23431858, 14558127, 10045474]
    if args.case == 'single-starter': hand = [20001443, 23431858, 14558127, 97268402, 10045474]
    opposing = {'name': 'TEST ONLY public BlueEyes opponent', 'deck': opponent, 'opening': opponent['main'][:5]}
    if args.case == 'ash':
        opposing = {'name': 'TEST ONLY controlled Ash opponent',
                    'deck': {'main': [14558127] * 3 + [1184620] * 37, 'extra': [], 'side': []},
                    'opening': [14558127] + [1184620] * 4}
    case_dir = LOCAL / 'evidence' / (args.case + '-' + time.strftime('%Y%m%d-%H%M%S'))
    case_dir.mkdir(parents=True, exist_ok=False)
    saved = api('/api/decks', {'name': 'TEST ONLY ygo-agent ' + uuid.uuid4().hex[:6], 'deck': deck})
    session = api('/api/start', {'deck_id': saved['id'], 'design': {
        'name': 'TEST ONLY ygo-agent pilot', 'notes': 'Public upstream deck; isolated CPU inference experiment',
        'revision': saved['revision'], 'conditions': {'hand_count': 5,
        'slots': hand, 'banned': []},
        'opponent_ai': True, 'opponent_responses': args.case == 'ash', 'opponent_config': opposing}})['id']
    evidence = {'case': args.case, 'opening': hand, 'opponent_responses': args.case == 'ash',
                'scope': 'first-turn CPU inference in isolated native free practice',
                'limitations': ['database base stats, not dynamic stats', 'no win-rate evaluation',
                    'no training', 'no production UI integration'], 'session': session, 'steps': []}
    try:
        folder = args.runtime / '_trainer/sessions' / session
        def current(after=-1):
            deadline = time.monotonic() + 25
            while time.monotonic() < deadline:
                try: state = json.loads((folder / 'modular-state.json').read_text(encoding='utf-8'))
                except (OSError, ValueError): state = None
                if state and state['version'] > after and not state['answered'] and state['player'] == 0:
                    raw = bytes.fromhex(state['raw'])
                    # The native UI acknowledges empty optional chains itself.
                    # They are not model decisions and must not enter RNN history.
                    if not (raw[0] == 16 and raw[2] == 0): return state
                time.sleep(.03)
            raise TimeoutError('Native decision not available')
        state = current()
        journal = folder / 'native.jsonl'
        with journal.open(encoding='utf-8') as source: header = json.loads(source.readline())
        if header.get('test_control') is not True:
            raise ValueError('Native test input must only target an explicitly marked acceptance session')
        (LOCAL / 'evidence/initial-state.json').write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding='utf-8')
        (LOCAL / 'evidence/session-path.txt').write_text(str(folder), encoding='utf-8')
        print('Native decision captured:', state['version'], 'prompt', bytes.fromhex(state['raw'])[0])
        print('Cards:', len(state['state']['cards']))
        from adapter import NativeInput
        from policy import Policy
        from app import Catalog
        policy, catalog = Policy(), Catalog(args.runtime).cards
        (case_dir / 'initial-input.json').write_text(json.dumps(NativeInput(state, catalog).input(), ensure_ascii=False, indent=2), encoding='utf-8')
        evidence['source_identity'] = json.loads((folder / 'session.json').read_text(encoding='utf-8'))
        began = time.perf_counter()
        for step in range(80):
            native = NativeInput(state, catalog)
            recommendation = policy.recommend(native)
            evidence['steps'].append(recommendation)
            print(f'{step+1:02d}. {recommendation["label"]} ({recommendation["inference_ms"]:.1f} ms)', flush=True)
            if native.prompt['message'] == 11 and recommendation['response'] == '07000000':
                evidence['status'] = 'model_recommended_end_turn'
                break
            actual = current()
            if (actual['version'], actual['raw']) != (state['version'], state['raw']):
                raise ValueError('Native state changed before the recommendation was executed')
            lease = uuid.uuid4().hex
            (folder / 'modular-lease.txt').write_text(lease, encoding='ascii')
            request = f'answer {state["version"]} {lease} 0 1\n{recommendation["response"]}\n'
            temporary = folder / 'pilot-request.tmp'
            temporary.write_text(request, encoding='ascii')
            temporary.replace(folder / 'modular.request')
            following = current(state['version'])
            if bytes.fromhex(following['raw'])[0] == 1:
                raise ValueError('Native engine rejected the response')
            result = json.loads((folder / 'modular-result.json').read_text(encoding='utf-8'))
            if result.get('token') != lease or result.get('status') != 'submitted':
                raise ValueError('Native engine did not acknowledge this exact response')
            policy.commit(state['version'], state['raw'], recommendation['response'])
            recommendation['engine_accepted'] = True
            recommendation['next_version'] = following['version']
            state = following
        else: evidence['status'] = 'decision_budget_reached'
        evidence['final_board'] = [{k: c[k] for k in ('code', 'name', 'controller', 'location', 'position')}
            for c in state['state']['cards'] if c['location'] in (2, 4, 8, 16, 32)]
        evidence['final_lp'] = state['state']['lp']
        evidence['elapsed_seconds'] = round(time.perf_counter() - began, 3)
        try:
            frame = api('/api/native/test', {'id': session, 'kind': 'capture'})
            with urllib.request.urlopen(args.url + frame['frame'], timeout=10) as response:
                (case_dir / 'final-board.png').write_bytes(response.read())
        except Exception as error:
            evidence['capture_error'] = str(error)
    except Exception as error:
        evidence['status'], evidence['error'] = 'blocked', f'{type(error).__name__}: {error}'
        raise
    finally:
        result_path = case_dir / 'result.json'
        result_path.write_text(json.dumps(evidence, ensure_ascii=False, indent=2), encoding='utf-8')
        api('/api/stop', {'id': session})
        deadline = time.monotonic() + 20
        while time.monotonic() < deadline:
            if not api('/api/modular/state/' + session).get('state', {}).get('running'): break
            time.sleep(.05)
        report = api('/api/report/' + session)
        (case_dir / 'report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
        from module_conditions import facts_from_report
        evidence['negations'] = [f for f in facts_from_report(report) if 'negated' in f['kind']]
        result_path.write_text(json.dumps(evidence, ensure_ascii=False, indent=2), encoding='utf-8')
        print('Evidence:', result_path, flush=True)


if __name__ == '__main__':
    main()
