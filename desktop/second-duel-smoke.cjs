'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');

module.exports=async function({page,application,root,evidence,pass}){
  const setup=await page.evaluate(async()=>{
    await api('/api/duel/settings',{hand_count:5});
    return api('/api/decks',{name:'TEST ONLY 后攻观察 '+crypto.randomUUID(),deck:{main:[14558127,...Array(39).fill(1184620)],extra:[],side:[]}});
  });
  const original=fs.readFileSync(path.join(root,'runtime','_trainer','decks',setup.id.split('/').at(-1)));
  await page.evaluate(async()=>{await switchModule('duel');await startNewDuel();});
  const click=async name=>{await page.locator(`[data-duel-action="${name}"]`).click();await page.waitForFunction(()=>!duelUI.busy);};
  await click('bo1');await click('manual');
  await page.locator(`[data-duel-deck="${setup.id}"]`).click();await page.waitForFunction(()=>!duelUI.busy);
  await click('start-duel');await click('second');
  await page.locator('[data-duel-add="14558127"]').click();
  for(let i=0;i<4;i++)await page.locator('[data-duel-add="1184620"]').click();
  await click('second-start');await page.waitForSelector('#second-workspace');
  const initial=await page.evaluate(()=>structuredClone(secondWorkspace().doc.input));
  assert.equal(await page.locator('#second-hand-count').textContent(),'5');
  const revision=async()=>page.evaluate(()=>secondWorkspace().doc.revision);
  const submit=async(form)=>{const before=await revision();await page.locator(`${form} button[type="submit"]`).click();await page.waitForFunction(n=>secondWorkspace().doc.revision>n&&!secondUI.busy,before);};
  const ash=await page.evaluate(()=>secondWorkspace().doc.current.cards.find(c=>c.code===14558127&&c.location===2).id);
  await page.locator(`#second-hand [data-second-card="${ash}"]`).click();
  await page.locator('#second-move-form [name="to"]').selectOption('16');
  await submit('#second-move-form');assert.equal(await page.locator('#second-hand-count').textContent(),'4');
  await submit('#second-draw-form');assert.equal(await page.locator('#second-hand-count').textContent(),'5');
  assert.deepEqual(await page.evaluate(()=>secondWorkspace().doc.input),initial);
  const verify=page.locator('#second-verify-form');
  await verify.locator('[name="turn"]').fill('2');await verify.locator('[name="turn_player"]').selectOption('0');
  await verify.locator('[name="phase"]').selectOption('main1');await verify.locator('[name="confirmed"]').check();
  await submit('#second-verify-form');assert.equal(await page.evaluate(()=>secondWorkspace().doc.status_reason),'');
  pass('Second-player UI: five opening cards, one spent hand trap, one actual draw, five current cards and unchanged immutable opening');

  await page.locator('summary').filter({hasText:'关键响应窗口与实际选择'}).click();
  await page.locator('#second-window-form [name="label"]').fill('TEST ONLY 对手已公开的效果，等待我方响应');
  await page.locator('#second-window-form [name="confirmed"]').check();await submit('#second-window-form');
  assert(await page.evaluate(()=>SecondDuelModel.validWindow(secondWorkspace().doc)));
  await page.locator('summary').filter({hasText:'关键响应窗口与实际选择'}).click();
  await page.locator('#second-note-form [name="note"]').fill('TEST ONLY 玩家选择不响应，对手继续处理');await submit('#second-note-form');
  assert.equal(await page.evaluate(()=>secondWorkspace().doc.current.window),null);
  assert.equal(await page.evaluate(()=>secondWorkspace().doc.events.at(-1).before.window.label),'TEST ONLY 对手已公开的效果，等待我方响应');
  const old=await page.evaluate(()=>SecondDuelModel.event(secondWorkspace().doc,'choice',{note:'迟到请求'},crypto.randomUUID().replaceAll('-','')));
  await page.locator('summary').filter({hasText:'录入对手公开卡牌'}).click();
  await page.locator('#second-opponent-form [name="unknown"]').check();
  await page.locator('#second-opponent-form [name="location"]').selectOption('8');await submit('#second-opponent-form');
  assert.equal(await page.evaluate(()=>secondWorkspace().doc.current.cards.find(c=>c.controller===1).code),null);
  const error=await page.evaluate(async body=>{try{await api('/api/second-duel/event',body);return '';}catch(error){return error.message;}},old);
  assert.match(error,/局面已更新/);
  pass('Response window, actual pass, unknown set card and late-revision rejection remain separate observations');

  await page.locator('#duel-steps [data-duel-stage="0"]').click();
  await click('second-history');assert(await page.locator('[data-second-action="resume"]').isVisible());
  await page.locator('[data-second-action="resume"]').click();
  await page.waitForFunction(()=>!secondUI.view&&!secondUI.busy&&secondWorkspace().doc.events.at(-1).kind==='resume');
  assert.equal(await page.locator('#second-hand-count').textContent(),'5');
  assert.equal(await page.evaluate(()=>secondWorkspace().doc.current.window),null);
  assert.match(await page.locator('#second-status').textContent(),/核对/);
  assert.deepEqual(await page.evaluate(()=>secondWorkspace().doc.input),initial);
  pass('History entry and explicit manual resume preserve resources while invalidating old windows');

  await page.screenshot({path:path.join(evidence,'second-current-state.png')});
  await application.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.getParentWindow()).setContentSize(900,650));
  await page.waitForFunction(()=>innerWidth===900);
  assert(await page.locator('#second-workspace').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await page.screenshot({path:path.join(evidence,'second-narrow-state.png')});
  await application.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.getParentWindow()).setContentSize(1280,900));
  await page.locator('[data-second-action="close"]').click();await page.waitForFunction(()=>secondWorkspace().doc.closed&&!secondUI.busy);
  assert.equal(await page.locator('#second-move-form').count(),0);
  const closed=await page.evaluate(()=>structuredClone(secondWorkspace().doc));
  const folder=path.join(root,'runtime','_trainer','second-duels');
  const stored=JSON.parse(fs.readFileSync(path.join(folder,closed.id+'.json'),'utf8'));
  assert.deepEqual(stored.input,initial);assert(stored.events.length>=7);
  assert.deepEqual(fs.readFileSync(path.join(root,'runtime','_trainer','decks',setup.id.split('/').at(-1))),original);
  await page.locator('[data-second-action="history"]').click();await page.waitForSelector('[data-second-history]');
  await page.locator(`[data-second-history="${closed.id}"]`).click();await page.waitForFunction(()=>!!secondUI.view);
  assert.equal(await page.locator('#second-verify-form').count(),0);
  await click('new');await click('bo1');await click('manual');
  await page.locator(`[data-duel-deck="${setup.id}"]`).click();await page.waitForFunction(()=>!duelUI.busy);
  await click('start-duel');await click('first');
  assert.equal(await page.locator('[data-duel-action="match"]').count(),1);
  assert.equal(await page.locator('#second-workspace').count(),0);
  pass('Observation history persists without changing deck files; narrow layout fits and original first-player entry remains available');
};
