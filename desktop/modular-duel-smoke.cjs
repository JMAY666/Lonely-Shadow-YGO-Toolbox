'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
module.exports=async({page,root,evidence,pass})=>{
  const source=JSON.parse(fs.readFileSync(path.join(evidence,'pipeline-source.json'),'utf8')),requests=[];
  const observe=request=>{if(request.url().endsWith('/api/modular/dispatch')&&request.method()==='POST')requests.push(request.postDataJSON());};
  page.on('request',observe);
  await page.evaluate(async source=>{
    await refreshHistory();await switchModule('duel');duelUI.state=newDuel();
    const s=duelState();s.deck=await api('/api/deck?id='+encodeURIComponent(source.deck));s.mode='BO1';s.first=true;s.count=3;s.hand=[1184620,1184620,1184620];
    s.result=await api('/api/duel/match',{deck_id:s.deck.id,revision:s.deck.revision,hand_count:3,hand:s.hand});s.stage=4;s.reached=4;renderDuel();
  },source);
  await page.locator('[data-duel-action="modular"]').click();
  await page.waitForFunction(()=>moduleUI.current==='duel'&&!!document.querySelector('#duel-brain-field')&&!!duelState().modularSession&&!moduleUI.switching,null,{timeout:60000});
  await page.waitForFunction(()=>document.querySelector('#duel-brain-search')?.disabled===false,null,{timeout:60000});
  const sid=await page.evaluate(()=>duelState().modularSession);
  await page.waitForFunction(()=>rewindState.data?.nodes?.length>0,null,{timeout:30000});
  const host=await page.evaluate(id=>api('/api/native/status?id='+id),sid);
  assert(host.visible&&host.frame_ready&&host.owns_stage_hit_test&&host.composition_compatible,'Duel must expose its actual native field');
  const capture=await page.evaluate(id=>api('/api/native/test',{id,kind:'capture'}),sid);
  const frame=await page.request.get(new URL(capture.frame,page.url()).href);
  fs.writeFileSync(path.join(evidence,'duel-brain-native.png'),await frame.body());
  const meta=JSON.parse(fs.readFileSync(path.join(root,'runtime','_trainer','sessions',sid,'session.json'),'utf8'));
  assert.deepEqual(meta.expansion.actual_opening,[1184620,1184620,1184620]);
  assert(await page.locator('#duel-brain-field #native-stage').count());
  await page.locator('#duel-brain-precise').check();
  await page.waitForFunction(()=>!!document.querySelector('#duel-brain-routes [data-modular-execute]'),null,{timeout:90000});
  assert.equal(await page.evaluate(()=>moduleUI.current),'duel');
  await page.screenshot({path:path.join(evidence,'duel-brain-dispatch.png'),preserveScroll:true});
  await page.locator('#duel-brain-auto').click();
  await page.waitForFunction(()=>duelUI.brainStatus?.reason==='已到达所选路线的实际终场'&&!duelUI.brainStatus.auto,null,{timeout:120000});
  const state=await page.evaluate(()=>duelUI.brainStatus.state.state);
  assert(state.cards.some(c=>c.controller===0&&c.location===4&&c.code===1184620));
  for(const intent of ['configure','search','auto','status'])assert(requests.some(r=>r.consumer==='duel'&&r.intent===intent));
  await page.locator('[data-duel-action="inspect-brain"]').click();await page.waitForFunction(()=>moduleUI.current==='modular'&&!moduleUI.switching);
  assert(await page.locator('#modular-data').innerText().then(text=>text.includes('卡组编辑')&&text.includes('展开与分支记录')));
  await page.locator('#module-duel').click();await page.waitForFunction(()=>moduleUI.current==='duel'&&!moduleUI.switching);
  assert.equal(await page.evaluate(()=>duelState().modularSession),sid);
  assert(await page.locator('#duel-brain-field #native-stage').count());
  await page.evaluate(()=>endDuel());await page.waitForFunction(()=>duelState().stage===6);
  assert(await page.locator('#training #native-stage').count());
  page.off('request',observe);
  pass('Deck editor and expansion feed the shared hub; Duel dispatches, executes and revisits one frozen live session with precise mode');
};
