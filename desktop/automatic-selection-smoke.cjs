'use strict';
const assert=require('node:assert/strict'),path=require('node:path');

module.exports=async function({page,application,evidence,pass,existing}) {
  const click=async action=>{await page.locator(`[data-duel-action="${action}"]`).click();await page.waitForFunction(()=>!duelUI.busy);};
  const navigate=async stage=>{await page.locator(`#duel-steps [data-duel-stage="${stage}"]`).click();};
  const before=await page.evaluate(async id=>({saved:await api('/api/deck?id='+encodeURIComponent(id)),editor:JSON.stringify(app.deck),active:app.active?.id||null}),existing.id);
  const writes=[],record=request=>{if(request.method()!=='GET'&&new URL(request.url()).pathname.startsWith('/api/'))writes.push(request.url());};
  page.on('request',record);
  try {
    await click('automatic');
    assert.equal(await page.locator('#duel-substeps [aria-current="step"]').getAttribute('data-duel-function-page'),'platform');
    assert.equal(await page.locator('.duel-mode').count(),1);
    assert(await page.evaluate(async()=>{const image=new Image();image.src='/brand/duel-ygopro.svg';await image.decode();return image.naturalWidth===600;}));
    const grid=await page.locator('.duel-platform-grid').boundingBox(),platform=await page.locator('.duel-platform').boundingBox();
    assert(Math.abs(platform.width-platform.height)<2);assert(Math.abs(platform.x+platform.width/2-grid.x-grid.width/2)<2);
    await page.screenshot({path:path.join(evidence,'duel-automatic-platform.png')});
    await click('platform-ygopro');
    assert.deepEqual(await page.locator('#duel-substeps button').allTextContents(),['1. 卡组识别','2. 卡牌预览']);
    assert(await page.locator('[data-duel-action="recognition-next"]').isDisabled());
    assert(await page.locator('[data-duel-deck-page="preview"]').isDisabled());
    await page.screenshot({path:path.join(evidence,'duel-automatic-empty.png')});
    await click('get-deck');
    assert.deepEqual(await page.evaluate(()=>zones.map(zone=>duelState().automatic.deck.deck[zone].length)),[40,4,9]);
    assert.equal(await page.locator('.duel-recognition-cards img').count(),53);
    await page.locator('.duel-recognition-cards img').evaluateAll(async images=>{for(const image of images){image.loading='eager';await image.decode();}});
    const left=await page.locator('.duel-recognition-panel').boundingBox(),right=await page.locator('.duel-recognition-controls').boundingBox();
    assert(right.x>=left.x+left.width);await page.screenshot({path:path.join(evidence,'duel-automatic-recognition.png')});
    await click('recognition-next');assert.equal(await page.locator('.duel-card').count(),53);
    for(const marker of ['main:0','extra:0','side:0']) {
      await page.locator(`[data-duel-mark-key="${marker}"] .review-card`).hover();
      await page.waitForFunction(()=>!document.querySelector('#toggle-duel-card-mark').hidden);
      await page.locator('#toggle-duel-card-mark').click();await page.locator('#review-detail-close').click();
    }
    assert.equal(await page.locator('.duel-card.is-marked').count(),3);
    assert.equal(await page.evaluate(()=>duelState().marks.size),0);
    await click('auto-tags');assert.equal(await page.locator('.duel-auto-tag-selected button').count(),3);
    await page.locator('[data-duel-auto-tag="demo-dragon"][data-role="primary"]').click();
    assert.equal(await page.locator('[data-duel-auto-tag="demo-dragon"][data-role="primary"]').getAttribute('aria-pressed'),'true');
    await page.locator('[data-duel-auto-tag="demo-fusion"][data-role=""]').click();
    await page.locator('#duel-auto-tag-search').fill('不存在');assert.equal(await page.locator('.duel-auto-tag-options button').count(),0);
    assert.equal(await page.locator('.duel-auto-tag-selected button').count(),2);await page.locator('#duel-auto-tag-search').fill('');
    await page.locator('#duel-auto-name').fill('');assert(await page.locator('#duel-auto-save').isDisabled());
    await page.locator('#duel-auto-name').fill('CON');await page.locator('#duel-auto-save').click();
    assert((await page.locator('#duel-auto-save-status').textContent()).includes('保留名称'));
    const name='自动流程演示';await page.locator('#duel-auto-name').fill(name);await page.locator('#duel-auto-name').press('Enter');
    assert((await page.locator('#duel-auto-save-status').textContent()).includes('已保存'));
    await page.locator('[data-duel-auto-tag="demo-ritual"][data-role="secondary"]').click();
    await page.locator('#duel-auto-save').click();assert(await page.locator('#duel-auto-overwrite').isVisible());
    await click('cancel-auto-overwrite');assert(await page.locator('#duel-auto-overwrite').isHidden());
    assert.equal(await page.evaluate(()=>duelState().automatic.saved[0].tag_selection.tag_ids.length),2);
    await page.locator('#duel-auto-save').click();await click('confirm-auto-overwrite');
    assert.equal(await page.evaluate(()=>duelState().automatic.saved.length),1);
    assert.equal(await page.evaluate(()=>duelState().automatic.saved[0].tag_selection.tag_ids.length),3);
    assert((await page.locator('#duel-auto-save-status').textContent()).includes('覆盖更新'));
    await page.locator('#duel-auto-name').fill(existing.name);await page.locator('#duel-auto-save').click();
    assert(await page.locator('#duel-auto-overwrite').isVisible());await click('confirm-auto-overwrite');
    await page.screenshot({path:path.join(evidence,'duel-automatic-preview.png')});
    await click('start-duel');assert.equal(await page.evaluate(()=>duelState().stage),2);
    assert((await page.locator('#duel-message').textContent()).includes('不会启动决斗'));
    assert(await page.locator('#duel-steps [data-duel-stage="3"]').isDisabled());
    await page.locator('[data-duel-deck-page="recognition"]').click();await click('get-deck');await click('recognition-next');
    assert.equal(await page.locator('#duel-auto-name').inputValue(),existing.name);
    assert.equal(await page.locator('.duel-card.is-marked').count(),3);
    await application.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.getParentWindow()).setContentSize(960,800));
    await page.waitForFunction(()=>innerWidth===960);
    assert(await page.locator('#duel').evaluate(el=>el.scrollWidth===el.clientWidth));
    const panel=await page.locator('.duel-auto-save-panel').boundingBox();assert(panel.x>=0&&panel.x+panel.width<=960);
    assert(panel.y+panel.height<=(await page.locator('#duel-footer').boundingBox()).y,'Save panel stays above the floating duel action');
    await page.locator('#duel-auto-save').scrollIntoViewIfNeeded();
    const save=await page.locator('#duel-auto-save').boundingBox();assert(save.y>=panel.y&&save.y+save.height<=panel.y+panel.height);
    await page.screenshot({path:path.join(evidence,'duel-automatic-preview-narrow.png')});
    await application.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.getParentWindow()).setContentSize(1280,900));
    await page.waitForFunction(()=>innerWidth===1280);
    await page.locator('#module-home').click();await page.waitForFunction(()=>moduleUI.current==='home'&&!moduleUI.switching);
    await page.locator('#module-duel').click();await page.waitForFunction(()=>moduleUI.current==='duel'&&!moduleUI.switching);
    assert.equal(await page.locator('#duel-auto-name').inputValue(),existing.name);
    await navigate(1);await page.locator('[data-duel-function-page="choice"]').click();await click('manual');
    assert.equal(await page.locator('.duel-recognition-panel').count(),0);
    assert.deepEqual(await page.locator('#duel-substeps button').allTextContents(),['1. 选择卡组','2. 卡牌预览']);
    assert.equal(await page.locator('#duel-substeps [aria-current="step"]').getAttribute('data-duel-deck-page'),'list');
    const after=await page.evaluate(async id=>({saved:await api('/api/deck?id='+encodeURIComponent(id)),editor:JSON.stringify(app.deck),active:app.active?.id||null}),existing.id);
    assert.deepEqual(after,before);assert.deepEqual(writes,[]);
    await navigate(1);
    pass('Automatic frontend: YGOPro platform, gated thumbnail recognition, shared card details and per-copy marks, AI TAG sample and manual roles, session save/confirmed same-name update, 960px layout and zero deck/engine writes');
  } finally {page.off('request',record);}
};
