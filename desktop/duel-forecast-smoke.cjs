'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
module.exports=async({page,root,evidence,pass})=>{
  const source=JSON.parse(fs.readFileSync(path.join(evidence,'pipeline-source.json'),'utf8'));
  const requests=[];const observe=request=>{if(request.url().endsWith('/api/modular/dispatch')&&request.method()==='POST')requests.push(request.postDataJSON());};page.on('request',observe);
  await page.evaluate(async source=>{
    await refreshHistory();await switchModule('duel');duelUI.state=newDuel();const s=duelState();
    s.deck=await api('/api/deck?id='+encodeURIComponent(source.deck));s.mode='BO1';s.first=true;s.count=3;s.hand=[1184620,1184620,1184620];
    s.result=await api('/api/duel/match',{deck_id:s.deck.id,revision:s.deck.revision,hand_count:s.count,hand:s.hand});s.stage=4;s.reached=4;renderDuel();
  },source);
  const history=await page.evaluate(()=>api('/api/history'));
  await page.locator('[data-duel-action="modular"]').click();
  await page.waitForFunction(()=>duelState().forecast&&!duelState().forecast.busy,null,{timeout:90000});
  assert.equal(await page.evaluate(()=>moduleUI.current),'duel');
  assert.equal(await page.locator('#duel #native-stage').count(),0);
  const diagnostic=await page.evaluate(()=>({error:duelState().forecast.error,data:duelState().forecast.data}));
  assert(diagnostic.data?.result?.candidates.length,JSON.stringify(diagnostic));
  const sid=diagnostic.data.id;
  assert.deepEqual(await page.evaluate(()=>api('/api/history')),history,'Planning never becomes an expansion or draft');
  const host=await page.evaluate(id=>api('/api/native/status?id='+id),sid);assert.equal(host.visible,false);
  const journal=path.join(root,'runtime','_trainer','sessions',sid,'native.jsonl'),before=fs.readFileSync(journal);
  await page.locator('[data-duel-adopt]').first().click();
  await page.waitForFunction(()=>duelState().stage===5&&duelState().plan?.temporary);
  assert(await page.locator('[data-duel-action="report-outcome"]').isVisible());
  await page.locator('[data-duel-node="main/final"]').click();
  await page.waitForFunction(()=>duelState().plan.confirmed===1);
  await page.locator('[data-duel-action="back-step"]').click();
  assert.equal(await page.evaluate(()=>duelState().plan.confirmed),1);
  await page.locator('[data-duel-action="forward-step"]').click();
  assert.equal(await page.evaluate(()=>duelState().plan.confirmed),1);
  assert.deepEqual(fs.readFileSync(journal),before,'User confirmation updates a forecast, never the real native input journal');
  await page.locator('[data-duel-action="back-step"]').click();
  await page.locator('[data-duel-action="report-outcome"]').click();
  await page.locator('#duel-observation-kind').selectOption('mill');
  await page.locator('#duel-observation-query').fill('1184620');
  await page.locator('[data-observation-code="1184620"]').click();
  await page.locator('#duel-observation-submit').click();
  await page.waitForFunction(()=>document.querySelector('#duel-observation-error').textContent.includes('不符'));
  assert.equal(await page.evaluate(()=>duelState().plan.confirmed),1,'An invalid correction preserves the route');
  await page.locator('#duel-observation-cancel').click();
  await page.screenshot({path:path.join(evidence,'duel-temporary-plan.png'),preserveScroll:true});
  assert(!requests.some(r=>['auto','execute'].includes(r.intent)));
  await page.evaluate(()=>endDuel());
  await page.waitForFunction(()=>duelState().stage===6);
  await page.waitForFunction(id=>api('/api/native/status?id='+id).then(s=>!s.ready),sid,{timeout:20000});
  assert.deepEqual(await page.evaluate(()=>api('/api/history')),history);
  page.off('request',observe);
  pass('Background temporary plan stays in Duel, adopts a step graph, confirms progress without live inputs, and preserves progress on invalid observations');
};
