'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
module.exports=async({page,application,evidence,pass})=>{
 const fixture=JSON.parse(fs.readFileSync(path.join(evidence,'second-battle-ui.json'),'utf8'));
 await page.evaluate(async id=>{await switchModule('duel');duelUI.state=newDuel();const s=duelState();s.mode='BO1';s.operationMode='manual';
   const doc=await api('/api/second-duel/state',{id});setSecondWorkspace({doc,generation:0});s.stage=duelStages.plans;s.reached=duelStages.plans;renderDuel();},fixture.id);
 await page.locator('#second-battle>summary').click();
 const before=await page.evaluate(()=>structuredClone(secondWorkspace().doc.current));
 const count=await page.evaluate(()=>secondWorkspace().doc.battle_history.length);
 await page.locator('#second-battle-form button[type="submit"]').click();
 await page.waitForFunction(n=>secondWorkspace().doc.battle_history.length===n+1&&!secondUI.busy,count,{timeout:60000});
 assert.deepEqual(await page.evaluate(()=>secondWorkspace().doc.current),before);
 const result=await page.evaluate(()=>secondWorkspace().doc.battle_history.at(-1).result);
 assert.equal(result.conditional_lethal,false);assert.equal(result.steps.length,0);assert.match(result.reason,/未开放/);
 assert.match(await page.locator('#second-battle').textContent(),/不代表必胜或最优/);
 const validity=await page.locator('.second-battle-validity').allTextContents();
 assert(validity.includes('基于当前节点'));assert(validity.includes('历史／过期节点'));
 await page.locator('#second-battle').scrollIntoViewIfNeeded();await page.screenshot({path:path.join(evidence,'second-battle.png'),preserveScroll:true});
 await application.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.getParentWindow()).setContentSize(900,650));
 await page.waitForFunction(()=>innerWidth===900);assert(await page.locator('#second-workspace').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 await page.screenshot({path:path.join(evidence,'second-battle-narrow.png'),preserveScroll:true});
 await page.evaluate(async()=>{await secondSubmit('close',{});});
 pass('Battle order UI preserves actual resources, refuses a spent attacker, marks old previews and keeps a narrow layout');
};
